import { expect, test, type Page } from '@playwright/test'
import { readFileSync } from 'node:fs'

const origin = 'http://127.0.0.1:5190'
const words = JSON.parse(readFileSync('public/dicts/IELTS_WANG_3.json', 'utf8')).slice(0, 3)
const stat = (page: Page, label: string) => page.getByText(label, { exact: true }).locator('..').locator('span').first()
const current = (page: Page) => page.locator('div[lang="en"] .tooltip-info > div').first()

test.beforeEach(async ({ context }) => {
  await context.addInitScript(() => {
    localStorage.setItem('currentDict', JSON.stringify('ieltsWang3'))
    localStorage.setItem('currentChapter', '0')
    localStorage.setItem('isTransVisible', 'false')
    localStorage.setItem('loopWordConfig', JSON.stringify({ times: 3 }))
    localStorage.setItem('wordDictationConfig', JSON.stringify({ isOpen: true, type: 'hideAll', openBy: 'user' }))
  })
  await context.route('https://**/*', (route) => route.abort())
  await context.route('**/dicts/IELTS_WANG_3.json', (route) => route.fulfill({ json: words }))
  await context.route('**/audio?**', (route) =>
    route.fulfill({ contentType: 'audio/wav', body: readFileSync('public/sounds/correct.wav') }),
  )
  await context.route('**/events', (route) => route.fulfill({ status: 204 }))
})

test('total words are fixed, only complete hidden words count, and repetitions do not inflate correct words', async ({ page }) => {
  await page.goto(origin)
  await expect(stat(page, '单词数')).toHaveText('3')
  await page.getByRole('button', { name: '开始', exact: true }).click()
  await page.keyboard.type('abil', { delay: 20 })
  await expect(stat(page, '正确数')).toHaveText('0')
  await page.keyboard.type('ity', { delay: 20 })
  await expect(stat(page, '正确数')).toHaveText('1')
  await expect(stat(page, '正确率')).toHaveText('33')
  for (let i = 0; i < 2; i++) {
    await expect(current(page)).toHaveText('_______')
    await page.keyboard.type('ability', { delay: 20 })
    await expect(stat(page, '正确数')).toHaveText('1')
  }
  await expect(current(page)).toHaveText('________')
  await expect(stat(page, '单词数')).toHaveText('3')
  await page.keyboard.type('abstract', { delay: 20 })
  await expect(stat(page, '正确数')).toHaveText('2')
  await expect(stat(page, '正确率')).toHaveText('67')
})

test('Tab or mouse answer exposure remains disqualifying after it is hidden again, without leaking to the next word', async ({ page }) => {
  await page.goto(origin)
  await page.getByRole('button', { name: '开始', exact: true }).click()
  await page.keyboard.down('Tab')
  await expect(current(page)).toHaveText('ability')
  await page.keyboard.up('Tab')
  await expect(current(page)).toHaveText('_______')
  await page.keyboard.type('ability', { delay: 20 })
  await expect(stat(page, '正确数')).toHaveText('0')
  // Completion feedback must still finish normally when a word was peeked.
  await expect(page.locator('div[lang="en"]').locator('..').getByText('能力', { exact: true })).toBeVisible()
  await expect(current(page)).toHaveText('_______')
  await page.keyboard.type('ability', { delay: 20 })
  await expect(stat(page, '正确数')).toHaveText('0')
  await page.keyboard.press('Control+Shift+ArrowRight')
  await expect(current(page)).toHaveText('________')
  await current(page).hover()
  await expect(current(page)).toHaveText('abstract')
  await page.mouse.move(0, 0)
  await page.keyboard.type('abstract', { delay: 20 })
  await expect(stat(page, '正确数')).toHaveText('0')
  await page.keyboard.press('Control+Shift+ArrowRight')
  await page.keyboard.type('accountant', { delay: 20 })
  await expect(stat(page, '正确数')).toHaveText('1')
  await expect(stat(page, '正确率')).toHaveText('33')
})

