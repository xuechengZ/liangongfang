test('an unseen correction can count, revisiting cannot count twice, and restarting clears the session', async ({ page }) => {
  await page.goto(origin)
  await page.getByRole('button', { name: '开始', exact: true }).click()
  await page.keyboard.type('x')
  await page.waitForTimeout(400)
  await page.keyboard.type('ability', { delay: 20 })
  await expect(stat(page, '正确数')).toHaveText('1')
  await page.keyboard.press('Control+Shift+ArrowRight')
  await page.keyboard.press('Control+Shift+ArrowLeft')
  await page.keyboard.type('ability', { delay: 20 })
  await expect(stat(page, '正确数')).toHaveText('1')
  await page.getByRole('button', { name: '暂停', exact: true }).hover()
  await page.getByRole('button', { name: '重新开始', exact: true }).click()
  await page.mouse.move(0, 0)
  await expect(stat(page, '正确数')).toHaveText('0')
  await expect(stat(page, '正确率')).toHaveText('0')
  await expect(stat(page, '单词数')).toHaveText('3')
  await page.keyboard.type('ability', { delay: 20 })
  await expect(stat(page, '正确数')).toHaveText('1')
})

test('skipped words stay in the denominator and the final screen uses the same word accuracy', async ({ page }) => {
  await page.addInitScript(() => localStorage.setItem('loopWordConfig', JSON.stringify({ times: 1 })))
  await page.goto(origin)
  await page.getByRole('button', { name: '开始', exact: true }).click()
  await page.keyboard.type('ability', { delay: 20 })
  await expect(current(page)).toHaveText('________')
  await page.keyboard.press('Control+Shift+ArrowRight')
  await expect(current(page)).toHaveText('__________')
  await page.keyboard.type('accountant', { delay: 20 })
  await expect(page.getByRole('button', { name: '重复本章节', exact: true })).toBeVisible()
  await expect(stat(page, '正确数')).toHaveText('2')
  await expect(stat(page, '单词数')).toHaveText('3')
  await expect(page.getByText('67%', { exact: true })).toBeVisible()
})

test('answers viewed in the chapter list cannot later count as unseen dictation', async ({ page }) => {
  await page.goto(origin)
  await page.getByRole('button', { name: '开始', exact: true }).click()
  await page.locator('button.fixed.left-0').click()
  const drawer = page.getByRole('dialog')
  await expect(drawer.getByText('ability', { exact: true })).toBeVisible()
  await expect(drawer.getByText('accountant', { exact: true })).toBeVisible()
  // Allow the real visibility observer to receive the displayed cards.
  await page.waitForTimeout(300)
  await drawer.locator('h3 svg').click()
  await page.keyboard.press('Enter')
  await page.keyboard.type('ability', { delay: 20 })
  await expect(stat(page, '正确数')).toHaveText('0')
  await expect(page.locator('div[lang="en"]').locator('..').getByText('能力', { exact: true })).toBeVisible()
})

